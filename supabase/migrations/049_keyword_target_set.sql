-- (engine.ts:310-325), and opportunity_score is PRESENCE-AMPLIFIED (calculateScore.ts:176-179 over
-- checkPresence.ts:150-161), so a keyword we will never cover carries a permanent x3 premium:
-- "art teacher clothes" (5,331/mo, opp 53) outranks "comfort colors tshirt" (306,496/mo, opp 14)
-- on B0GF49RLDL purely BECAUSE we do not cover it. No relevance classifier can out-argue that
-- arithmetic, which is why PRs #441/#442 (RELEVANCE_THEME_V2) caught zero on a live re-research.
--
-- theme_fit is a JUDGMENT SIGNAL (LLM). selection_rank is a DERIVED SELECTION (pure deterministic
-- function of the signals + raw market math, recomputed on every storeAnalysis). action_type is
-- NEVER rewritten: there is no IRRELEVANT-style ratchet here (ai-recommendations/route.ts:903-907
-- has no reverse path anywhere in the codebase and once permanently demoted a seller's top money
-- keyword). Additive + nullable: with KEYWORD_TARGET_SET=off every read is byte-identical to today.

